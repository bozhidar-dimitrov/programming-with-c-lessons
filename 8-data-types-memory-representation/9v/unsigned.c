#include <stdio.h>

int main(void) {

  char a = 250;
  printf("%d\n", a);

  unsigned char b = 250;
  printf("%u\n", b);

  unsigned short c = 2342;
  printf("%hu\n", c);

  unsigned int c1 = 32423;
  printf("%u\n", c1);

  unsigned long d = 234234;
  printf("%lu\n", d);

  unsigned long long d1 = 324234;
  printf("%llu\n", d1);

  return 0;
}